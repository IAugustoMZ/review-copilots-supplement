"""`review-cli db ...` -- schema migration, inspection, and git-tracked snapshots.

`snapshot`/`restore` exist because of the 2026-08-28 data loss: review.db held
~698 human topical decisions and ~1378 dimension classification rows -- the only
artefact in this pipeline that cannot be regenerated by re-running it -- in a
single gitignored file with no backup, and the working tree was deleted. See
docs/SAMPLING_AND_AGREEMENT.md and the .gitignore comment above
`review_pipeline/data/normalized/`.

The DB itself is too big to track directly (139MB at 7.8k records; the
`raw_metadata_json` provenance column alone is ~108MB, and platform limits cut
in at 100MB per file), but it gzips to ~27MB, so the tracked artefact is
`review.db.gz` and the live file stays ignored.
"""

from __future__ import annotations

import gzip
import json
import shutil
from pathlib import Path

import typer
from rich.console import Console
from rich.table import Table as RichTable
from sqlalchemy import inspect, text

from review_pipeline.src.common.config import DEFAULT_DB_PATH
from review_pipeline.src.db.engine import get_engine, pending_migrations, run_migrations
from review_pipeline.src.fulltext.blob_sync import (
    connection_string_from_env,
    container_name_from_env,
    push_file_to_blob,
)

db_app = typer.Typer(help="Schema migration and inspection.")
console = Console()

_ENTITY_TABLES = [
    "records",
    "search_runs",
    "query_hits",
    "authors",
    "record_authors",
    "fulltext_locations",
    "preprint_matches",
    "duplicate_groups",
    "classifications_ai",
    "classifications_human",
    "classifications_final",
    "screening_decisions",
    "verified_evidence",
    "sentinel_records",
    "gap_searches",
    "audit_events",
    "reviewer_sessions",
    "corpus_snapshots",
    "documented_exceptions",
]


@db_app.command("migrate")
def migrate() -> None:
    """Apply any pending schema migrations."""
    engine = get_engine()
    applied = run_migrations(engine)
    if applied:
        console.print(f"[green]Applied {len(applied)} migration(s):[/green] {', '.join(applied)}")
    else:
        console.print("[dim]Database already up to date. No migrations applied.[/dim]")


@db_app.command("status")
def status() -> None:
    """Show migration state and row counts per table."""
    engine = get_engine()
    raw_conn = engine.raw_connection()
    try:
        sqlite_conn = raw_conn.driver_connection
        pending = pending_migrations(sqlite_conn)
    finally:
        raw_conn.close()

    console.print(f"[bold]Database:[/bold] {DEFAULT_DB_PATH}")
    if pending:
        console.print(
            f"[yellow]{len(pending)} pending migration(s):[/yellow] "
            f"{', '.join(p.name for p in pending)} -- run `review-cli db migrate`."
        )
    else:
        console.print("[green]Schema up to date.[/green]")

    table = RichTable(title="Row counts")
    table.add_column("Table")
    table.add_column("Rows", justify="right")
    with engine.connect() as conn:
        for table_name in _ENTITY_TABLES:
            try:
                count = conn.execute(text(f"SELECT COUNT(*) FROM {table_name}")).scalar_one()
            except Exception:  # noqa: BLE001 -- best-effort row count for an inspection command
                count = "-"
            table.add_row(table_name, str(count))
    console.print(table)


DEFAULT_SNAPSHOT_PATH = Path(str(DEFAULT_DB_PATH) + ".gz")
# gzip level 6 is the default and the right trade here: level 9 buys under 3% on
# this data for several times the CPU, on a file rewritten at every milestone.
_SNAPSHOT_COMPRESSLEVEL = 6


def _mb(path: Path) -> float:
    return path.stat().st_size / 1024 / 1024


@db_app.command("snapshot")
def snapshot(
    output: str = typer.Option(str(DEFAULT_SNAPSHOT_PATH), "--output", help="Where to write the compressed snapshot."),
) -> None:
    """Compress the live DB to a git-trackable snapshot. Run at every pipeline milestone."""
    output = Path(output)
    if not DEFAULT_DB_PATH.exists():
        console.print(f"[red]No database at {DEFAULT_DB_PATH}[/red] -- run `review-cli db migrate` first.")
        raise typer.Exit(1)

    output.parent.mkdir(parents=True, exist_ok=True)
    # Write to a temp file and move into place, so an interrupted run cannot
    # leave a truncated snapshot sitting where a restore would trust it.
    staging = output.with_suffix(output.suffix + ".partial")
    with DEFAULT_DB_PATH.open("rb") as src, gzip.open(staging, "wb", compresslevel=_SNAPSHOT_COMPRESSLEVEL) as dst:
        shutil.copyfileobj(src, dst)
    staging.replace(output)

    live_mb, snap_mb = _mb(DEFAULT_DB_PATH), _mb(output)
    console.print(
        f"[green]Snapshot written:[/green] {output} "
        f"({live_mb:.0f}MB -> {snap_mb:.0f}MB, {snap_mb / live_mb:.0%} of original)"
    )
    console.print(
        "[dim]Now push it off-machine: `review-cli db blob-push`. It is too large for git "
        "(100MB per-file limit); `db export-human` is what git carries.[/dim]"
    )


@db_app.command("restore")
def restore(
    source: str = typer.Option(str(DEFAULT_SNAPSHOT_PATH), "--source", help="Compressed snapshot to restore from."),
    force: bool = typer.Option(False, "--force", help="Overwrite an existing database."),
) -> None:
    """Decompress a snapshot back into the live DB path."""
    source = Path(source)
    if not source.exists():
        console.print(f"[red]No snapshot at {source}[/red]")
        raise typer.Exit(1)
    if DEFAULT_DB_PATH.exists() and not force:
        console.print(
            f"[red]{DEFAULT_DB_PATH} already exists.[/red] Restoring would discard it -- "
            f"pass --force if that is what you want."
        )
        raise typer.Exit(1)

    DEFAULT_DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    staging = DEFAULT_DB_PATH.with_suffix(DEFAULT_DB_PATH.suffix + ".partial")
    with gzip.open(source, "rb") as src, staging.open("wb") as dst:
        shutil.copyfileobj(src, dst)
    staging.replace(DEFAULT_DB_PATH)
    console.print(f"[green]Restored:[/green] {source} -> {DEFAULT_DB_PATH} ({_mb(DEFAULT_DB_PATH):.0f}MB)")


# The irreplaceable part of this database is small. Everything else -- records,
# search runs, AI classifications -- is regenerable by re-running the pipeline;
# the human decisions are two days of a person's judgement that no re-run can
# reproduce. They are exported on their own so git can carry them at KB scale,
# diffable and versioned per commit, while the full snapshot (90MB at 26.8k
# records, and growing past the 100MB platform limit) goes to Azure Blob
# Storage alongside the PDF cache.
HUMAN_TABLES = (
    "classifications_human",
    "classifications_final",
    "screening_decisions",
    "reviewer_sessions",
    "documented_exceptions",
)
DEFAULT_HUMAN_EXPORT_PATH = DEFAULT_DB_PATH.parent / "human_classifications.json.gz"
DEFAULT_SNAPSHOT_BLOB_NAME = "review.db.gz"


@db_app.command("export-human")
def export_human(
    output: str = typer.Option(str(DEFAULT_HUMAN_EXPORT_PATH), "--output", help="Where to write the compressed export."),
) -> None:
    """Export the human-made decisions to a small, git-trackable JSON file."""
    output = Path(output)
    engine = get_engine()
    payload: dict[str, list[dict]] = {}
    present = set(inspect(engine).get_table_names())
    with engine.connect() as conn:
        # A table absent from an older schema is skipped rather than fatal, so
        # this stays usable against a snapshot taken before a migration.
        for table_name in (t for t in HUMAN_TABLES if t in present):
            rows = conn.execute(text(f"SELECT * FROM {table_name}")).mappings().all()
            payload[table_name] = [dict(r) for r in rows]

    output.parent.mkdir(parents=True, exist_ok=True)
    staging = output.with_suffix(output.suffix + ".partial")
    with gzip.open(staging, "wt", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=1, sort_keys=True, default=str)
    staging.replace(output)

    table = RichTable(title="Human decisions exported")
    table.add_column("Table")
    table.add_column("Rows", justify="right")
    for table_name, rows in payload.items():
        table.add_row(table_name, str(len(rows)))
    console.print(table)
    console.print(f"[green]Written:[/green] {output} ({output.stat().st_size / 1024:.0f}KB) -- commit it.")


@db_app.command("blob-push")
def blob_push(
    source: str = typer.Option(str(DEFAULT_SNAPSHOT_PATH), "--source", help="Compressed snapshot to upload."),
    blob_name: str = typer.Option(DEFAULT_SNAPSHOT_BLOB_NAME, "--blob-name", help="Blob name in the container."),
) -> None:
    """Upload the compressed DB snapshot to Azure Blob Storage (Cool tier)."""
    source = Path(source)
    if not source.exists():
        console.print(f"[red]No snapshot at {source}[/red] -- run `review-cli db snapshot` first.")
        raise typer.Exit(1)

    connection_string = connection_string_from_env()
    container_name = container_name_from_env()
    if not connection_string or not container_name:
        console.print(
            "[red]Azure credentials missing.[/red] Set AZURE_STORAGE_CONNECTION_STRING and "
            "AZURE_STORAGE_CONTAINER in review_v2/.env (see .env.example)."
        )
        raise typer.Exit(1)

    outcome = push_file_to_blob(connection_string, container_name, source, blob_name=blob_name)
    if outcome.status == "failed":
        console.print(f"[red]Upload failed:[/red] {outcome.error}")
        raise typer.Exit(1)
    console.print(
        f"[green]{outcome.status}:[/green] {blob_name} -> container {container_name} "
        f"({outcome.size_bytes / 1024 / 1024:.0f}MB, Cool tier)"
    )
